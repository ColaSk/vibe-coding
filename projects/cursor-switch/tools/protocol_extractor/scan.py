"""Scan Cursor JS bundles for Connect/gRPC style service paths and type names."""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path

SERVICE_PATH = re.compile(
    r"/(?:aiserver|agent|auth)\.v\d+\.[A-Za-z0-9_]+/[A-Za-z0-9_]+"
)
MESSAGE_NAME = re.compile(
    r"\b((?:aiserver|agent)\.v\d+\.[A-Za-z][A-Za-z0-9_]*)\b"
)

BUNDLE_NAMES = (
    "workbench.desktop.main.js",
    "extensionHostProcess.js",
)


@dataclass
class ExtractionResult:
    inputs: list[str] = field(default_factory=list)
    services: list[str] = field(default_factory=list)
    messages: list[str] = field(default_factory=list)


def discover_bundles(root: Path) -> list[Path]:
    if root.is_file():
        return [root]
    found: list[Path] = []
    candidates = [
        root / "Contents/Resources/app/out/vs/workbench/workbench.desktop.main.js",
        root / "Contents/Resources/app/out/vs/workbench/api/node/extensionHostProcess.js",
        root / "Resources/app/out/vs/workbench/workbench.desktop.main.js",
        root / "Resources/app/out/vs/workbench/api/node/extensionHostProcess.js",
        root / "out/vs/workbench/workbench.desktop.main.js",
        root / "out/vs/workbench/api/node/extensionHostProcess.js",
    ]
    for path in candidates:
        if path.is_file():
            found.append(path)
    for name in BUNDLE_NAMES:
        for path in root.rglob(name):
            if "node_modules" in path.parts:
                continue
            found.append(path)
    # de-dupe while preserving order
    seen: set[Path] = set()
    unique: list[Path] = []
    for path in found:
        resolved = path.resolve()
        if resolved in seen:
            continue
        seen.add(resolved)
        unique.append(resolved)
    return unique


def scan_text(text: str) -> tuple[set[str], set[str]]:
    services = set(SERVICE_PATH.findall(text))
    messages = set(MESSAGE_NAME.findall(text))
    return services, messages


def extract(paths: list[Path]) -> ExtractionResult:
    services: set[str] = set()
    messages: set[str] = set()
    inputs: list[str] = []
    for path in paths:
        text = path.read_text(encoding="utf-8", errors="ignore")
        found_services, found_messages = scan_text(text)
        services |= found_services
        messages |= found_messages
        inputs.append(str(path))
    return ExtractionResult(
        inputs=inputs,
        services=sorted(services),
        messages=sorted(messages),
    )


def render_proto_inventory(result: ExtractionResult) -> str:
    lines = [
        'syntax = "proto3";',
        "",
        "// Generated by tools/protocol_extractor.",
        "// This is an inventory stub from Cursor JS bundles, not full field layouts.",
        "// Replace with richer extraction or hand-authored messages as needed.",
        "",
        "package cursor.switch.inventory;",
        "",
    ]
    for service_path in result.services:
        # /aiserver.v1.Foo/Bar -> service Foo { rpc Bar ... }
        trimmed = service_path.strip("/")
        package_and_service, _, method = trimmed.rpartition("/")
        service = package_and_service.rsplit(".", 1)[-1]
        lines.append(f"// path: {service_path}")
        lines.append(f"service {service}Inventory {{")
        lines.append(f"  rpc {method} (google.protobuf.Empty) returns (google.protobuf.Empty);")
        lines.append("}")
        lines.append("")
    if result.messages:
        lines.append("// Observed fully-qualified message / type names:")
        for name in result.messages:
            lines.append(f"// - {name}")
        lines.append("")
    return "\n".join(lines)
